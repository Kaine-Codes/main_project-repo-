                f_vec.append(np.sum(hfd50 * w_norm))

                # Wigner (1 feature)
                f_vec.append(np.sum(wig * w_norm))

                # Global (4 features: VN, Ent, QFI, E_Change)
                f_vec.extend([vn, ent, qfi, e_change])

                # Total: 9+3+2+1+4 = 19 Features
                row = [t_glob, file_info['segment']] + f_vec + y
