class RealTimeInferenceEngine:
    def __init__(self, model_path, scaler_path):
        print(f"{Colors.CYAN}Initializing Engine & Loading Model...{Colors.RESET}")
        self.model = tf.keras.models.load_model(
            model_path,
            custom_objects={'weighted_kl_loss': weighted_kl_loss},
            safe_mode=False
        )
        self.scaler = joblib.load(scaler_path)
        self.reset_state() # Initialize buffers

    def reset_state(self):
        """Clears all buffers and memory states for a new EDF file."""
        self.seq_buffer = deque(maxlen=SEQ_LEN)
        self.prob_buffer = deque(maxlen=3)
        self.vn_buffer = deque(maxlen=5)

        self.current_state = "NORMAL"
        self.prev_cov = None
        self.prev_energy = None

        # Reset Filter States
        b_bp, a_bp = butter(4, [0.5, 80], btype='band', fs=SFREQ)
        b_n, a_n = iirnotch(60, 30, fs=SFREQ)
        self.filters = {'bp': (b_bp, a_bp), 'notch': (b_n, a_n)}

        zi_bp = lfilter_zi(b_bp, a_bp)
        zi_n = lfilter_zi(b_n, a_n)
        self.zi_bp = np.tile(zi_bp, (18, 1))
        self.zi_n = np.tile(zi_n, (18, 1))

    def decide_state(self, probs):
        p_int, p_pre, p_ict, p_post = probs
        if p_ict > TH_ICT: return "ICTAL"
        elif p_pre > TH_PRE: return "PREICTAL"
        elif (p_int > TH_NORMAL) or (p_post > TH_NORMAL): return "NORMAL"
        return None  # NO SWITCH

    def process_window(self, raw_window_18ch):
        b_bp, a_bp = self.filters['bp']
        b_n, a_n = self.filters['notch']
        filtered, self.zi_bp = lfilter(b_bp, a_bp, raw_window_18ch, axis=1, zi=self.zi_bp)
        filtered, self.zi_n = lfilter(b_n, a_n, filtered, axis=1, zi=self.zi_n)

        w = compute_focal_weights(filtered)
        w_norm = w / (np.sum(w) + 1e-9)

        spec_feats, ch_energy = compute_extended_spectral(filtered, SFREQ)
        curr_energy = np.sum(ch_energy * w_norm)
        e_change = abs(curr_energy - self.prev_energy) if self.prev_energy is not None else 0.0
        self.prev_energy = curr_energy

        hjorth = compute_hjorth(filtered)
        hfd6 = np.array([higuchi_fd(ch, 6) for ch in filtered])
        hfd50 = np.array([higuchi_fd(ch, 50) for ch in filtered])
        wig = wigner_skew_proxy(filtered)
        vn, ent, qfi, cov = quantum_features(filtered, self.prev_cov)
        self.prev_cov = cov

        # Delta VN (Ensures 20 features

        # Aggregation (Must be exactly 20 features)
        f_vec = []
        for i in range(9): f_vec.append(np.sum(spec_feats[:, i] * w_norm)) # 9
        for i in range(3): f_vec.append(np.sum(hjorth[:, i] * w_norm))    # 3
        f_vec.append(np.sum(hfd6 * w_norm))                                # 1
        f_vec.append(np.sum(hfd50 * w_norm))                               # 1
        f_vec.append(np.sum(wig * w_norm))                                 # 1
        f_vec.extend([vn, ent, qfi, e_change])                   # 4 -> Total 19

        f_vec = np.array(f_vec).reshape(1, -1)
        f_vec_scaled = self.scaler.transform(f_vec)

        self.seq_buffer.append(f_vec_scaled[0])

        if len(self.seq_buffer) == SEQ_LEN:
            input_tensor = np.array(self.seq_buffer).reshape(1, SEQ_LEN, -1)
            probs = self.model.predict(input_tensor, verbose=0)[0]

            self.prob_buffer.append(probs)
            avg_probs = np.mean(self.prob_buffer, axis=0)

            new_state = self.decide_state(avg_probs)
            if new_state is not None:
                self.current_state = new_state

            return avg_probs, self.current_state

        return None, None

