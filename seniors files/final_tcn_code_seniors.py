def generate_data_driven_groups(csv_files, corr_threshold=0.75):
    print(f"\n--- PHASE 2: DYNAMIC FEATURE GROUPING ---")
    df_list = [pd.read_csv(f) for f in csv_files if os.path.exists(f)]
    if not df_list: return None

    full_df = pd.concat(df_list, ignore_index=True)
    corr_matrix = full_df[FEATURE_NAMES].corr(method='spearman')
    dist_matrix = np.clip(1.0 - np.abs(corr_matrix.values), 0, 1)
    np.fill_diagonal(dist_matrix, 0)

    linkage_matrix = hierarchy.linkage(squareform(dist_matrix), method='complete')
    cluster_labels = hierarchy.fcluster(linkage_matrix, t=(1.0 - corr_threshold), criterion='distance')

    dynamic_groups = {}
    for feat_name, clus_id in zip(FEATURE_NAMES, cluster_labels):
        g_name = f"Cluster_{clus_id}"
        if g_name not in dynamic_groups: dynamic_groups[g_name] = []
        dynamic_groups[g_name].append(feat_name)

    print(f"Clustering found {len(dynamic_groups)} independent feature groups based on collinearity.")
    return dynamic_groups

