def fast_state_machine(probs, th_pre, th_ict=0.8, th_normal=0.6):
    # Reverted to 3 windows (6 seconds) to make the model highly reactive
    prob_buffer = deque(maxlen=3)
    states = []
    current_state = "NORMAL"
    for p in probs:
        prob_buffer.append(p)
        avg = np.median(prob_buffer, axis=0) # Changed from np.mean to np.median

        if avg[2] > th_ict: current_state = "ICTAL"
        elif avg[1] > th_pre: current_state = "PREICTAL"
        elif avg[0] > th_normal or avg[3] > th_normal: current_state = "NORMAL"
        states.append(current_state)
    return states

def calculate_metrics(timeline_states, timeline_times, true_seizures):
    pre_events = []
    in_pre = False; start_t = 0
    for t, state in zip(timeline_times, timeline_states):
        if state == "PREICTAL" and not in_pre: in_pre = True; start_t = t
        elif state != "PREICTAL" and in_pre: in_pre = False; pre_events.append((start_t, t))
    if in_pre: pre_events.append((start_t, timeline_times[-1]))

    tp, fp = 0, 0
    lead_times = []
    matched = set()
    for onset, offset in true_seizures:
        predicted = False
        for i, (p_start, p_end) in enumerate(pre_events):
            if p_start <= onset and p_end >= (onset - 3600):
                if not predicted:
                    tp += 1
                    lead_times.append(onset - max(p_start, onset - 3600))
                    predicted = True
                matched.add(i)
    fp = len(pre_events) - len(matched)
    total_hours = (timeline_times[-1] - timeline_times[0]) / 3600.0 if len(timeline_times) > 0 else 0
    return tp, fp, total_hours, lead_times

def optimize_thresholds(probs, times, files, file_seizures):
    best_score = -999
    best_th_pre, best_th_ict, best_th_norm = 0.8, 0.8, 0.6

    # Create an exhaustive multi-dimensional grid of thresholds
    grid_combinations = []
    for t_pre in np.arange(0.50, 0.90, 0.05):
        for t_ict in np.arange(0.70, 0.95, 0.05):
            for t_norm in np.arange(0.40, min(t_pre + 0.1, 0.85), 0.05):
                grid_combinations.append((t_pre, t_ict, t_norm))

    print(f"Running Comprehensive Grid Search ({len(grid_combinations)} logical combinations)...")

    for t_pre, t_ict, t_norm in tqdm(grid_combinations, leave=False):
        total_tp, total_fp, total_sz, total_hrs = 0, 0, 0, 0
        for fname in np.unique(files):
            mask = (files == fname)
            states = fast_state_machine(probs[mask], th_pre=t_pre, th_ict=t_ict, th_normal=t_norm)
            sz_list = file_seizures.get(fname, [])
            tp, fp, hrs, _ = calculate_metrics(states, times[mask], sz_list)

            total_tp += tp; total_fp += fp; total_hrs += hrs; total_sz += len(sz_list)

        sens = (total_tp / total_sz) if total_sz > 0 else 0
        fpr = (total_fp / total_hrs) if total_hrs > 0 else 0

        # Fix: Heavily penalize False Alarms to prevent the optimizer from picking "greedy" thresholds
        # A penalty of 1.5 means allowing just 1 false alarm per hour costs the model 150% in the fitness score!
        # This strictly forces the models (especially the highly reactive TCN) to prioritize clinical safety.
        score = sens - (fpr * 1.5)

        if score > best_score:
            best_score = score
            best_th_pre, best_th_ict, best_th_norm = t_pre, t_ict, t_norm

    return best_th_pre, best_th_ict, best_th_norm

def evaluate_froc(probs, times, files, file_seizures):
    froc_pts = []
    for t_pre in tqdm(np.linspace(0.1, 0.95, 20), desc="Generating FROC", leave=False):
        t_norm = max(0.1, t_pre - 0.2)
        t_ict = min(0.95, t_pre + 0.1)
        total_tp, total_fp, total_sz, total_hrs = 0, 0, 0, 0
        for fname in np.unique(files):
            mask = (files == fname)
            states = fast_state_machine(probs[mask], th_pre=t_pre, th_ict=t_ict, th_normal=t_norm)
            sz_list = file_seizures.get(fname, [])
            tp, fp, hrs, _ = calculate_metrics(states, times[mask], sz_list)
            total_tp += tp; total_fp += fp; total_hrs += hrs; total_sz += len(sz_list)

        sens = (total_tp / total_sz)*100 if total_sz > 0 else 0
        fpr = (total_fp / total_hrs) if total_hrs > 0 else 0
        froc_pts.append((fpr, sens))
    return np.array(froc_pts)

