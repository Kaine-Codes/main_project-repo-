def build_causal_tcn(input_shape):
    """
    Restored to the exact original architecture proposed in the study
    to ensure scientific consistency across all experiments.
    """
    inputs = tf.keras.Input(shape=input_shape)
    x = inputs
    for d in [1, 2, 4, 8, 16, 32]:
        res = x
        x = tf.keras.layers.Conv1D(64, 3, padding='causal', dilation_rate=d, activation='relu')(x)
        x = tf.keras.layers.LayerNormalization()(x)
        x = tf.keras.layers.SpatialDropout1D(0.2)(x)
        if res.shape[-1] != 64: res = tf.keras.layers.Conv1D(64, 1)(res)
        x = tf.keras.layers.Add()([x, res])

    x = tf.keras.layers.Lambda(lambda t: t[:, -1, :])(x)
    x = tf.keras.layers.Dense(32, activation='relu')(x)
    outputs = tf.keras.layers.Dense(4, activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs, name="Causal_TCN")
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-4), loss=weighted_kl_loss, metrics=['accuracy'])
    return model

def build_lstm(input_shape):
    inputs = tf.keras.Input(shape=input_shape)
    x = tf.keras.layers.LSTM(64, return_sequences=True)(inputs)
    x = tf.keras.layers.Dropout(0.3)(x)
    x = tf.keras.layers.LSTM(32, return_sequences=False)(x)
    x = tf.keras.layers.Dense(32, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
    outputs = tf.keras.layers.Dense(4, activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs, name="LSTM")
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-4), loss=weighted_kl_loss, metrics=['accuracy'])
    return model

def build_cnn(input_shape):
    inputs = tf.keras.Input(shape=input_shape)
    x = tf.keras.layers.Conv1D(64, 3, padding='same', activation='relu')(inputs)
    x = tf.keras.layers.MaxPooling1D(2)(x)
    x = tf.keras.layers.Conv1D(128, 3, padding='same', activation='relu')(x)
    x = tf.keras.layers.GlobalAveragePooling1D()(x)
    x = tf.keras.layers.Dense(32, activation='relu', kernel_regularizer=tf.keras.regularizers.l2(1e-4))(x)
    outputs = tf.keras.layers.Dense(4, activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs, name="Standard_CNN")
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-4), loss=weighted_kl_loss, metrics=['accuracy'])
    return model

