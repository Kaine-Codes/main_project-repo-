@numba.jit(nopython=True)
def higuchi_fd(x, kmax):
    n_times = x.shape[0]
    lk = np.empty(kmax); x_reg = np.empty(kmax); y_reg = np.empty(kmax)
    for k in range(1, kmax + 1):
        lm = 0.0
        for m in range(k):
            ll = 0.0
            n_max = int(np.floor((n_times - m - 1) / k))
            for j in range(1, n_max + 1): ll += abs(x[m + j * k] - x[m + (j - 1) * k])
            ll /= k; ll *= (n_times - 1) / (k * n_max); lm += ll
        lk[k - 1] = lm / k; x_reg[k - 1] = np.log(1.0 / k); y_reg[k - 1] = np.log(lk[k - 1])
    x_mean = np.mean(x_reg); y_mean = np.mean(y_reg)
    num = np.sum((x_reg - x_mean) * (y_reg - y_mean))
    den = np.sum((x_reg - x_mean) ** 2)
    return num / den

def compute_extended_spectral(data, fs):
    freqs, psd = welch(data, fs, nperseg=fs, axis=-1)
    delta = np.sum(psd[:, (freqs>=0.5) & (freqs<4)], axis=1)
    theta = np.sum(psd[:, (freqs>=4) & (freqs<8)], axis=1)
    alpha = np.sum(psd[:, (freqs>=8) & (freqs<13)], axis=1)
    beta  = np.sum(psd[:, (freqs>=13) & (freqs<30)], axis=1)
    gamma = np.sum(psd[:, (freqs>=30) & (freqs<45)], axis=1)
    total = delta + theta + alpha + beta + gamma + 1e-10
    e = 1e-10
    r1 = theta/(delta+e); r2 = alpha/(theta+e); r3 = beta/(alpha+e); r4 = gamma/(beta+e)
    r5 = delta/(alpha+e); r6 = delta/(beta+e); r7 = theta/(beta+e)
    rel_d = delta/total; rel_t = theta/total
    return np.stack([r1, r2, r3, r4, r5, r6, r7, rel_d, rel_t], axis=1), total

def compute_hjorth(data):
    n_ch = data.shape[0]; res = np.zeros((n_ch, 3))
    for i in range(n_ch):
        x = data[i, :]; dx = np.diff(x); ddx = np.diff(dx)
        var_x = np.var(x); var_dx = np.var(dx); var_ddx = np.var(ddx)
        mob = np.sqrt(var_dx / (var_x + 1e-10))
        comp = np.sqrt(var_ddx / (var_dx + 1e-10)) / (mob + 1e-10)
        res[i, :] = [var_x, mob, comp]
    return res

def wigner_skew_proxy(data): return skew(np.abs(hilbert(data, axis=-1)), axis=-1)

def quantum_features(window, prev_cov):
    cov = np.cov(window); tr = np.trace(cov); rho = cov / (tr + 1e-10)
    eig = np.linalg.eigvalsh(rho); eig = eig[eig > 1e-12]
    vn_ent = -np.sum(eig * np.log(eig))
    rho_L = rho[0:8, 0:8]; rho_L = rho_L / (np.trace(rho_L) + 1e-10)
    eig_L = np.linalg.eigvalsh(rho_L); eig_L = eig_L[eig_L > 1e-12]
    ent_ent = -np.sum(eig_L * np.log(eig_L))
    qfi = 0.0
    if prev_cov is not None: qfi = np.sum((rho - (prev_cov/(np.trace(prev_cov)+1e-10)))**2)
    return vn_ent, ent_ent, qfi, cov

def compute_focal_weights(window):
    corr = np.corrcoef(window); np.nan_to_num(corr, copy=False, nan=0.0)
    mean_corr = np.mean(np.abs(corr), axis=1)
    weights = np.ones(window.shape[0])
    weights[mean_corr < 0.3] = 0.1
    return weights

def get_label(t, seizures):
    y = [1, 0, 0, 0]
    for (sz_start, sz_end) in seizures:
        if sz_start <= t <= sz_end: return [0, 0, 1, 0]
        if sz_end < t <= sz_end + 600: return [0, 0, 0, 1]
        if sz_start - 1200 <= t < sz_start:
            dist = sz_start - t
            if dist <= 60: return [0, 0.4, 0.6, 0]
            conf = max(0.2, 1.0 - (dist / 1200))
            return [1-conf, conf, 0, 0]
    return y

def extract_and_save_test_features():
    print("\n--- PHASE 1: DATA EXTRACTION (Caching to CSV) ---")
    b_bp, a_bp = butter(4, [0.5, 80], btype='band', fs=SFREQ)
    b_n, a_n = iirnotch(60, 30, fs=SFREQ)

    std_montage = ['FP1-F7', 'F7-T7', 'T7-P7', 'P7-O1', 'FP1-F3', 'F3-C3', 'C3-P3', 'P3-O1',
                   'FP2-F4', 'F4-C4', 'C4-P4', 'P4-O2', 'FP2-F8', 'F8-T8', 'T8-P8', 'P8-O2', 'FZ-CZ', 'CZ-PZ']

    for fname, info in CHB08_TEST_FILES.items():
        out_csv = os.path.join(CSV_CACHE_FOLDER, fname.replace('.edf', '.csv'))
        if os.path.exists(out_csv):
            print(f"Skipping {fname} (Already extracted in cache).")
            continue

        f_path = os.path.join(EDF_FOLDER, fname)
        if not os.path.exists(f_path):
            print(f"ERROR: Could not find {f_path}.")
            continue

        print(f"Extracting features for {fname}...")
        try:
            f = pyedflib.EdfReader(f_path)
            labels = f.getSignalLabels()
            indices = [next((i for i, l in enumerate(labels) if t in l), None) for t in std_montage]
            raw = np.zeros((18, f.getNSamples()[0]))
            for i, idx in enumerate(indices): raw[i, :] = f.readSignal(idx)
            f.close()

            filtered = lfilter(b_bp, a_bp, raw, axis=1)
            filtered = lfilter(b_n, a_n, filtered, axis=1)

            features = []
            win_pts = int(WINDOW_SEC * SFREQ)
            stride_pts = int(STRIDE_SEC * SFREQ)
            prev_cov = None; prev_energy = None

            for start in range(0, filtered.shape[1] - win_pts, stride_pts):
                t_sec = start / SFREQ
                window = filtered[:, start:start+win_pts]

                w = compute_focal_weights(window)
                w_norm = w / (np.sum(w) + 1e-9)

                spec_feats, ch_energy = compute_extended_spectral(window, SFREQ)
                curr_energy = np.sum(ch_energy * w_norm)
                e_change = abs(curr_energy - prev_energy) if prev_energy is not None else 0.0
                prev_energy = curr_energy

                hjorth = compute_hjorth(window)
                hfd6 = np.array([higuchi_fd(ch, 6) for ch in window])
                hfd50 = np.array([higuchi_fd(ch, 50) for ch in window])
                wig = wigner_skew_proxy(window)
                vn, ent, qfi, cov = quantum_features(window, prev_cov)
                prev_cov = cov

                f_vec = []
                for i in range(9): f_vec.append(np.sum(spec_feats[:, i] * w_norm))
                for i in range(3): f_vec.append(np.sum(hjorth[:, i] * w_norm))
                f_vec.extend([np.sum(hfd6 * w_norm), np.sum(hfd50 * w_norm), np.sum(wig * w_norm)])
                f_vec.extend([vn, ent, qfi, e_change])

                y = get_label(t_sec, info['seizures'])
                features.append([t_sec] + f_vec + y)

            cols = ['time_sec'] + FEATURE_NAMES + ['y_int', 'y_pre', 'y_ict', 'y_post']
            pd.DataFrame(features, columns=cols).to_csv(out_csv, index=False)
            print(f" -> Saved {len(features)} windows to {out_csv}")
        except Exception as e:
            print(f"Failed processing {fname}: {e}")


