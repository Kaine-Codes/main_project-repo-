# @title 3. Global Timeline Builder (Handles Gaps & Cross-File Seizures)

def hms_to_seconds(hms_str):
    """Converts '13:05:00' to seconds."""
    parts = list(map(int, hms_str.split(':')))
    return parts[0] * 3600 + parts[1] * 60 + parts[2]

class GlobalTimeline:
    def __init__(self, summary_path):
        self.files = []
        self.seizures = []
        self.segments = []
        self._parse_summary(summary_path)

    def _parse_summary(self, path):
        if not os.path.exists(path): return

        with open(path, 'r', encoding='latin-1') as f:
            content = f.read()

        # 1. Summary Parsing
        file_blocks = re.split(r'File Name:\s+', content)

        cumulative_offset = 0
        last_clock_time = 0
        current_day_offset = 0
        segment_id = 0
        last_file_end_global = 0

        for block in file_blocks:
            if not block.strip(): continue

            # Extract Name
            name_match = re.match(r'(\S+\.edf)', block)
            if not name_match: continue
            fname = name_match.group(1)

            # Extract Start Time (HH:MM:SS)
            time_match = re.search(r'File Start Time:\s+(\d+:\d+:\d+)', block)
            if not time_match:
                # Fallback: Assume continuous if time missing
                file_start_global = last_file_end_global
            else:
                clock_sec = hms_to_seconds(time_match.group(1))

                # Handle Midnight Crossing (e.g., 23:59 -> 00:01)
                if clock_sec < last_clock_time - 3600: # If time jumped back significantly
                    current_day_offset += 24 * 3600

                last_clock_time = clock_sec
                file_start_global = clock_sec + current_day_offset

            # Check for Gaps (Discontinuous Recording)
            if abs(file_start_global - last_file_end_global) > 10 and last_file_end_global != 0:
                segment_id += 1

            file_info = {
                'name': fname,
                'global_start': file_start_global,
                'global_end': -1, # To be filled by EDF reader
                'segment': segment_id
            }

            # Pattern: "Seizure 1 Start Time: 360 seconds"
            starts = re.findall(r'Seizure\s*(?:\d+)?\s*Start Time:\s*(\d+)\s*seconds', block)
            ends = re.findall(r'Seizure\s*(?:\d+)?\s*End Time:\s*(\d+)\s*seconds', block)

            for s, e in zip(starts, ends):
                g_start = file_start_global + int(s)
                g_end = file_start_global + int(e)
                self.seizures.append((g_start, g_end))

            self.files.append(file_info)

            # Approximate end for loop continuity (updated later)
            last_file_end_global = file_start_global + 3600 # Assume 1h if unknown

    def get_label(self, global_time):
        """
        Returns label vector [Inter, Pre, Ictal, Post] for a specific GLOBAL timestamp.
        """
        # Default: Interictal
        y = [1, 0, 0, 0]

        for (sz_start, sz_end) in self.seizures:
            # Ictal
            if sz_start <= global_time <= sz_end:
                return [0, 0, 1, 0]

            # Postictal (10 mins after)
            if sz_end < global_time <= sz_end + CONFIG['postictal_dur']:
                return [0, 0, 0, 1]

            # Preictal (20 mins before)
            if sz_start - CONFIG['preictal_dur'] <= global_time < sz_start:
                dist = sz_start - global_time
                if dist <= CONFIG['ambig_dur']: # Buffer
                    return [0, 0.4, 0.6, 0]
                else:
                    conf = 1.0 - (dist / CONFIG['preictal_dur'])
                    conf = max(0.2, conf)
                    return [1-conf, conf, 0, 0]

        return y

    def update_file_duration(self, fname, duration_sec):
        """Called by EDF reader to fix precise end times."""
        for f in self.files:
            if f['name'] == fname:
                f['global_end'] = f['global_start'] + duration_sec

