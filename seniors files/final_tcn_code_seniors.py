@tf.keras.utils.register_keras_serializable()
def weighted_recall(y_true, y_pred):
    y_true_cls = tf.argmax(y_true, axis=-1)
    y_pred_cls = tf.argmax(y_pred, axis=-1)

    recalls = []
    weights = [0.1, 0.55, 0.2, 0.15]

    for i in range(4):
        mask = tf.equal(y_true_cls, i)
        correct = tf.logical_and(mask, tf.equal(y_pred_cls, i))
        recall = tf.reduce_sum(tf.cast(correct, tf.float32)) / (tf.reduce_sum(tf.cast(mask, tf.float32)) + 1e-7)
