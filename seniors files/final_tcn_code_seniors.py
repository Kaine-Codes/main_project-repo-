@tf.keras.utils.register_keras_serializable()
def weighted_kl_loss(y_true, y_pred):
    weights = tf.constant([1.0, 10.0, 15.0, 4.0])
    y_true = tf.clip_by_value(y_true, 1e-7, 1.0)
    y_pred = tf.clip_by_value(y_pred, 1e-7, 1.0)
    return tf.reduce_sum((y_true * tf.math.log(y_true / y_pred)) * weights, axis=-1)

def extract_sequences(file_list, scaler_path, mode='test'):
    """Extracts X (N, 120, 19), y (N, 4), and timelines for evaluation."""
    X_list, y_list, time_list, file_track = [], [], [], []

    available_files = [f for f in file_list if os.path.exists(os.path.join(CSV_CACHE_FOLDER, f))]
    if not available_files:
        print(f"Warning: No files found for {mode} split in {CSV_CACHE_FOLDER}")
        return None, None, None, None

    df_list = [pd.read_csv(os.path.join(CSV_CACHE_FOLDER, f)) for f in available_files]
    full_df = pd.concat(df_list, ignore_index=True)

    if mode == 'train':
        scaler = RobustScaler()
        scaler.fit(full_df[FEATURE_NAMES])
        joblib.dump(scaler, scaler_path)
    else:
        scaler = joblib.load(scaler_path)

    print(f"Extracting {mode} sequences...")
    for df, fname in zip(tqdm(df_list, desc=f"{mode.capitalize()} Files"), available_files):
        df[FEATURE_NAMES] = scaler.transform(df[FEATURE_NAMES])
        feats = df[FEATURE_NAMES].values
        labels = df[['y_int', 'y_pre', 'y_ict', 'y_post']].values
