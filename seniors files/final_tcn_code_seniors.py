class SegmentAwareGenerator(tf.keras.utils.Sequence):
    def __init__(self, csv_files, seq_len=120, batch_size=32, scaler=None, mode='train'):
        self.seq_len = seq_len
        self.batch_size = batch_size
        self.mode = mode

        # 1. Load Data
        data_list = []
        for f in csv_files:
            # Check Output Path (Ensure OUTPUT_PATH is defined in Cell 2)
            p = os.path.join(OUTPUT_PATH, f)
            if os.path.exists(p):
                data_list.append(pd.read_csv(p))
            else:
                print(f"Warning: File not found {p}")

        if not data_list:
            raise ValueError("No data found. Did you run the Preprocessing (Cell 5)?")

        # 2. Concatenate & Clean
        self.df = pd.concat(data_list, ignore_index=True)
        self.df.fillna(0, inplace=True)

        # 3. Columns Setup
        # Structure: [global_time, segment_id, ...features..., y_int, y_pre, y_ict, y_post]
        # Features start at index 2, Labels are last 4
        self.feat_cols = self.df.columns[2:-4]
        self.label_cols = self.df.columns[-4:]

        # 4. Scaling
        if scaler is None:
            self.scaler = RobustScaler()
            self.df[self.feat_cols] = self.scaler.fit_transform(self.df[self.feat_cols])
        else:
            self.scaler = scaler
            self.df[self.feat_cols] = self.scaler.transform(self.df[self.feat_cols])

        # 5. Calculate Valid Indices (No Gap Crossing)
        self.indices = []

        # Vectorized check for segment continuity
        seg_ids = self.df['segment_id'].values
        total_len = len(self.df)

        potential_starts = np.arange(total_len - seq_len)

        if len(potential_starts) > 0:
            start_segs = seg_ids[potential_starts]
            end_segs = seg_ids[potential_starts + seq_len - 1]

            mask = (start_segs == end_segs)
            self.indices = potential_starts[mask]
        else:
            self.indices = np.array([])

        if mode == 'train' and len(self.indices) > 0:
            y_pre = self.df[self.label_cols[1]].values
            y_ict = self.df[self.label_cols[2]].values
            end_indices = self.indices + seq_len - 1
            target_mask = (y_pre[end_indices] > 0.3) | (y_ict[end_indices] > 0.0)

            target_idxs = self.indices[target_mask]

            if len(target_idxs) > 0:
                self.indices = np.concatenate([self.indices] + [target_idxs]*3)
                np.random.shuffle(self.indices)

    def __len__(self):
        return int(len(self.indices) // self.batch_size)

    def __getitem__(self, idx):
        batch_idxs = self.indices[idx*self.batch_size : (idx+1)*self.batch_size]

        X = np.zeros((self.batch_size, self.seq_len, len(self.feat_cols)))
        y = np.zeros((self.batch_size, 4))

        for i, start_i in enumerate(batch_idxs):
            # Slice sequence
            X[i] = self.df.iloc[start_i : start_i+self.seq_len][self.feat_cols].values
            # Label is the state at the END of the sequence
            y[i] = self.df.iloc[start_i + self.seq_len - 1][self.label_cols].values

        return X, y

