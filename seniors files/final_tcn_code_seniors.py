def fast_state_machine(probs, th_pre=0.6, th_ict=0.8, th_normal=0.6):
    prob_buffer = deque(maxlen=3)
    states = []
    current_state = "NORMAL"
    for p in probs:
        prob_buffer.append(p)
        avg = np.mean(prob_buffer, axis=0)
        if avg[2] > th_ict: current_state = "ICTAL"
        elif avg[1] > th_pre: current_state = "PREICTAL"
        elif avg[0] > th_normal or avg[3] > th_normal: current_state = "NORMAL"
        states.append(current_state)
    return states

def calculate_metrics(timeline_states, timeline_times, true_seizures):
    preictal_events = []
    in_pre = False; start_t = 0
    for t, state in zip(timeline_times, timeline_states):
        if state == "PREICTAL" and not in_pre: in_pre = True; start_t = t
        elif state != "PREICTAL" and in_pre: in_pre = False; preictal_events.append((start_t, t))
    if in_pre: preictal_events.append((start_t, timeline_times[-1]))

    metrics = {"TP": 0, "FP": 0, "Misses": 0, "Lead_Times": []}
    matched = set()

    for onset, offset in true_seizures:
        predicted = False
        for i, (p_start, p_end) in enumerate(preictal_events):
            if p_start <= onset and p_end >= (onset - 3600):
                if not predicted:
                    metrics["TP"] += 1
                    metrics["Lead_Times"].append(onset - max(p_start, onset - 3600))
                    predicted = True
                matched.add(i)
        if not predicted: metrics["Misses"] += 1

    metrics["FP"] = len(preictal_events) - len(matched)
    metrics["Total_Alarms"] = len(preictal_events)

    return {
        "TP": metrics["TP"], "FP": metrics["FP"], "Misses": metrics["Misses"],
        "Total_Alarms": metrics["Total_Alarms"], "Lead_Times": metrics["Lead_Times"]
    }

