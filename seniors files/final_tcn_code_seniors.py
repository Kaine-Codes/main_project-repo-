def process_folder(target_folder, model_path, scaler_path, output_csv):
    if not os.path.exists(target_folder):
        print(f"{Colors.RED}Error: Folder not found {target_folder}{Colors.RESET}")
        return

    # Find all EDFs
    edf_files = sorted(glob.glob(os.path.join(target_folder, '*.edf')))
    if not edf_files:
        print(f"{Colors.RED}No EDF files found in {target_folder}{Colors.RESET}")
        return

    print(f"{Colors.CYAN}Found {len(edf_files)} EDF files. Starting batch processing...{Colors.RESET}")

    engine = RealTimeInferenceEngine(model_path, scaler_path)

    # Storage for CSV
    all_results = []

    for edf_path in edf_files:
        fname = os.path.basename(edf_path)

        # 1. Reset memory for the new file
        engine.reset_state()

        print("\n" + "="*80)
        print(f"{Colors.CYAN}📁 STARTING FILE: {fname}{Colors.RESET}")
        print("="*80)

        try:
            f = pyedflib.EdfReader(edf_path)
        except Exception as e:
            print(f"{Colors.RED}Failed to read {fname}: {e}{Colors.RESET}")
            continue

        # Map Channels
        labels = f.getSignalLabels()
        indices = []
        for tgt in STD_MONTAGE:
            match = next((i for i, l in enumerate(labels) if tgt in l), None)
            if match is None:
                print(f"{Colors.RED}Missing channel {tgt}. Skipping file.{Colors.RESET}")
                f.close()
                break
            indices.append(match)

        if len(indices) != len(STD_MONTAGE):
            continue # Skipped due to missing channel

        # Load Data
        fs = f.getSampleFrequency(0)
        ns = f.getNSamples()[0]
        step = max(1, int(fs / SFREQ))

        print("Buffering Raw Data into RAM...")
        raw = np.zeros((18, ns // step))
        for i, idx in enumerate(indices):
            raw[i, :] = f.readSignal(idx)[::step]
        f.close()

        win_pts = int(WINDOW_SEC * SFREQ)
        stride_pts = int(STRIDE_SEC * SFREQ)

        last_logged_state = None

        # Iterate Windows
        for start in range(0, raw.shape[1] - win_pts, stride_pts):
            t_cur = start / SFREQ
            window = raw[:, start:start+win_pts]

            probs, state = engine.process_window(window)

            if probs is not None:
                # Format print color
                c = Colors.GREEN if state == "NORMAL" else (Colors.YELLOW if state == "PREICTAL" else Colors.RED)

                # Check if state changed OR if it's the very first prediction
                if state != last_logged_state:
                    p_str = f"[{probs[0]:.2f}, {probs[1]:.2f}, {probs[2]:.2f}, {probs[3]:.2f}]"

                    if last_logged_state is None:
                        print(f"{t_cur:06.1f}s | {Colors.CYAN}Initial State Detected:{Colors.RESET} {c}{state:<10}{Colors.RESET} | {p_str}")
                    else:
                        print(f"{t_cur:06.1f}s | {Colors.YELLOW}STATE CHANGE:{Colors.RESET} -> {c}{state:<10}{Colors.RESET} | {p_str}")

                    last_logged_state = state

                # Save per-window data to our list
                all_results.append({
                    'File': fname,
                    'Time_sec': round(t_cur, 1),
                    'State_Decision': state,
                    'Prob_Interictal': round(probs[0], 4),
                    'Prob_Preictal': round(probs[1], 4),
                    'Prob_Ictal': round(probs[2], 4),
                    'Prob_Postictal': round(probs[3], 4)
                })

        print(f"{Colors.CYAN}✅ END OF FILE: {fname} (Processed {t_cur:.1f} seconds){Colors.RESET}")

    # After processing all files, save the CSV
    if all_results:
        df = pd.DataFrame(all_results)
        df.to_csv(output_csv, index=False)
        print("\n" + "="*80)
        print(f"{Colors.GREEN}🎉 BATCH PROCESSING COMPLETE! Saved per-window predictions to:{Colors.RESET}")
        print(f" -> {output_csv}")
        print("="*80)
    else:
        print(f"{Colors.RED}No valid predictions generated to save.{Colors.RESET}")

