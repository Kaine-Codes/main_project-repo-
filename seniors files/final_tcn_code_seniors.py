# --- CAUSAL FILTERS ---
def get_causal_filters(fs):
    b_bp, a_bp = butter(4, [0.5, 80], btype='band', fs=fs)
    b_notch, a_notch = iirnotch(60, 30, fs=fs)
    return (b_bp, a_bp), (b_notch, a_notch)

def apply_causal_filters(data, filters):
    (b_bp, a_bp), (b_notch, a_notch) = filters
    data = lfilter(b_bp, a_bp, data, axis=-1)
    data = lfilter(b_notch, a_notch, data, axis=-1)
    return data

