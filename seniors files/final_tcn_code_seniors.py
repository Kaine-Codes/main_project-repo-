def weighted_kl_loss(y_true, y_pred):
    weights = tf.constant([2.0, 5.0, 8.0, 3.0])
    y_true = tf.clip_by_value(y_true, 1e-7, 1.0)
    y_pred = tf.clip_by_value(y_pred, 1e-7, 1.0)
    kl = y_true * tf.math.log(y_true / y_pred)
    return tf.reduce_sum(kl * weights, axis=-1)

@tf.keras.utils.register_keras_serializable()
def weighted_recall(y_true, y_pred):
    y_true_cls = tf.argmax(y_true, axis=-1)
    y_pred_cls = tf.argmax(y_pred, axis=-1)

    recalls = []
    eights = [0.1, 0.55, 0.2, 0.15]

    for i in range(4):
        mask = tf.equal(y_true_cls, i)
        correct = tf.logical_and(mask, tf.equal(y_pred_cls, i))
        recall = tf.reduce_sum(tf.cast(correct, tf.float32)) / (tf.reduce_sum(tf.cast(mask, tf.float32)) + 1e-7)
        recalls.append(recall)

    recalls = tf.stack(recalls)
    weights = tf.constant(weights, dtype=tf.float32)

    return tf.reduce_sum(recalls * weights)

def build_causal_tcn(input_shape):
    # input_shape (SEQ_LEN, 19)
    inputs = tf.keras.Input(shape=input_shape)
    x = inputs

    # 6 Blocks = 2^6 = 64 dilation
    for d in [1, 2, 4, 8, 16, 32]:
        res = x
        x = tf.keras.layers.Conv1D(64, 3, padding='causal', dilation_rate=d)(x)
        x = tf.keras.layers.LayerNormalization()(x)
        x = tf.keras.layers.Activation('relu')(x)
        x = tf.keras.layers.SpatialDropout1D(0.2)(x)

        x = tf.keras.layers.Conv1D(64, 3, padding='causal', dilation_rate=d)(x)
        x = tf.keras.layers.LayerNormalization()(x)
        x = tf.keras.layers.Activation('relu')(x)
        x = tf.keras.layers.SpatialDropout1D(0.2)(x)

        if res.shape[-1] != 64:
            res = tf.keras.layers.Conv1D(64, 1)(res)
        x = tf.keras.layers.Add()([x, res])

    x = tf.keras.layers.Lambda(lambda t: t[:, -1, :])(x)
    x = tf.keras.layers.Dense(32, activation='relu')(x)
    x = tf.keras.layers.Dropout(0.3)(x)
    outputs = tf.keras.layers.Dense(4, activation='softmax')(x)

    model = tf.keras.Model(inputs, outputs)
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-4),
                  loss=weighted_kl_loss,
                  metrics=[
                      'accuracy',
                      tf.keras.metrics.Recall(class_id=0, name='inter_recall'),
                      tf.keras.metrics.Recall(class_id=1, name='pre_recall'),
                      tf.keras.metrics.Recall(class_id=2, name='ictal_recall'),
                      tf.keras.metrics.Recall(class_id=3, name='post_recall'),
                      weighted_recall
                  ]
                  )
    return model

