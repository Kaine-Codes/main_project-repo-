            n_stride = int(CONFIG['stride'] * CONFIG['sfreq'])

            prev_cov = None
            prev_energy = None

            for start in range(0, filtered.shape[1] - n_win, n_stride):
                window = filtered[:, start:start+n_win]
                t_glob = file_info['global_start'] + (start / CONFIG['sfreq'])
                y = timeline.get_label(t_glob)

                # Weights
                w = compute_focal_weights(window)
                w_norm = w / (np.sum(w) + 1e-9)

                # 1. Extended Spectral (9 feats + energy)
                spec_feats, ch_energy = compute_extended_spectral(window, CONFIG['sfreq'])

                # 2. Hjorth (3 feats: Act, Mob, Comp)
                hjorth = compute_hjorth(window)

                # 3. Energy Change (Global Temporal)
                # Weighted sum of channel energies
                curr_energy = np.sum(ch_energy * w_norm)
                if prev_energy is None:
                    e_change = 0.0
                else:
                    e_change = abs(curr_energy - prev_energy)
                prev_energy = curr_energy

                # 4. Other
                hfd6 = np.array([higuchi_fd(ch, 6) for ch in window])
                hfd50 = np.array([higuchi_fd(ch, 50) for ch in window])
                wig = wigner_skew_proxy(window)
                vn, ent, qfi, cov = quantum_features(window, prev_cov)
                prev_cov = cov

                # --- AGGREGATION ---
                f_vec = []

                # Spectral (9 features)
                for i in range(9):
                    f_vec.append(np.sum(spec_feats[:, i] * w_norm))

                # Hjorth (3 features)
