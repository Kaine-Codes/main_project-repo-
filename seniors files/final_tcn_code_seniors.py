def quantum_features(window, prev_cov):
    cov = np.cov(window); tr = np.trace(cov); rho = cov / (tr + 1e-10)
    eig = np.linalg.eigvalsh(rho); eig = eig[eig > 1e-12]
    vn_ent = -np.sum(eig * np.log(eig))
    rho_L = rho[0:8, 0:8]; rho_L = rho_L / (np.trace(rho_L) + 1e-10)
    eig_L = np.linalg.eigvalsh(rho_L); eig_L = eig_L[eig_L > 1e-12]
    ent_ent = -np.sum(eig_L * np.log(eig_L))
    qfi = 0.0
    if prev_cov is not None: qfi = np.sum((rho - (prev_cov/(np.trace(prev_cov)+1e-10)))**2)
    return vn_ent, ent_ent, qfi, cov

