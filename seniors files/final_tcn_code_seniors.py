@numba.jit(nopython=True)
def higuchi_fd(x, kmax):
    n_times = x.shape[0]
    lk = np.empty(kmax)
    x_reg = np.empty(kmax)
    y_reg = np.empty(kmax)
    for k in range(1, kmax + 1):
        lm = 0.0
        for m in range(k):
            ll = 0.0
            n_max = int(np.floor((n_times - m - 1) / k))
            for j in range(1, n_max + 1):
                ll += abs(x[m + j * k] - x[m + (j - 1) * k])
            ll /= k
            ll *= (n_times - 1) / (k * n_max)
            lm += ll
        lk[k - 1] = lm / k
        x_reg[k - 1] = np.log(1.0 / k)
        y_reg[k - 1] = np.log(lk[k - 1])
    x_mean = np.mean(x_reg)
    y_mean = np.mean(y_reg)
    num = np.sum((x_reg - x_mean) * (y_reg - y_mean))
    den = np.sum((x_reg - x_mean) ** 2)
    return num / den

def compute_extended_spectral(data, fs):
    freqs, psd = welch(data, fs, nperseg=fs, axis=-1)
    delta = np.sum(psd[:, (freqs>=0.5) & (freqs<4)], axis=1)
    theta = np.sum(psd[:, (freqs>=4) & (freqs<8)], axis=1)
    alpha = np.sum(psd[:, (freqs>=8) & (freqs<13)], axis=1)
    beta  = np.sum(psd[:, (freqs>=13) & (freqs<30)], axis=1)
    gamma = np.sum(psd[:, (freqs>=30) & (freqs<45)], axis=1)
    total = delta + theta + alpha + beta + gamma + 1e-10
    e = 1e-10
    r1 = theta/(delta+e); r2 = alpha/(theta+e); r3 = beta/(alpha+e); r4 = gamma/(beta+e)
    r5 = delta/(alpha+e); r6 = delta/(beta+e); r7 = theta/(beta+e)
    rel_d = delta/total; rel_t = theta/total
    feats = np.stack([r1, r2, r3, r4, r5, r6, r7, rel_d, rel_t], axis=1)
    return feats, total

def compute_hjorth(data):
    n_ch = data.shape[0]
    res = np.zeros((n_ch, 3))
    for i in range(n_ch):
        x = data[i, :]
        dx = np.diff(x); ddx = np.diff(dx)
        var_x = np.var(x); var_dx = np.var(dx); var_ddx = np.var(ddx)
        act = var_x
        mob = np.sqrt(var_dx / (var_x + 1e-10))
        comp = np.sqrt(var_ddx / (var_dx + 1e-10)) / (mob + 1e-10)
        res[i, :] = [act, mob, comp]
    return res

def wigner_skew_proxy(data):
    analytic = hilbert(data, axis=-1)
    return skew(np.abs(analytic), axis=-1)

def quantum_features(window, prev_cov):
    cov = np.cov(window)
    tr = np.trace(cov)
    rho = cov / (tr + 1e-10)
    eig = np.linalg.eigvalsh(rho)
    eig = eig[eig > 1e-12]
    vn_ent = -np.sum(eig * np.log(eig))
    rho_L = rho[0:8, 0:8]
    rho_L = rho_L / (np.trace(rho_L) + 1e-10)
    eig_L = np.linalg.eigvalsh(rho_L)
    eig_L = eig_L[eig_L > 1e-12]
    ent_ent = -np.sum(eig_L * np.log(eig_L))
    qfi = 0.0
    if prev_cov is not None:
        tr_prev = np.trace(prev_cov)
        rho_prev = prev_cov / (tr_prev + 1e-10)
        qfi = np.sum((rho - rho_prev)**2)
    return vn_ent, ent_ent, qfi, cov

def compute_focal_weights(window):
    n_ch = window.shape[0]
    weights = np.ones(n_ch)
    with np.errstate(divide='ignore', invalid='ignore'):
        corr = np.corrcoef(window)
    np.nan_to_num(corr, copy=False, nan=0.0)
    mean_corr = np.mean(np.abs(corr), axis=1)
    for i in range(n_ch):
        if mean_corr[i] < 0.3:
            nbs = NEIGHBORS.get(i, [])
            nb_corrs = [np.abs(corr[i, n]) for n in nbs]
            max_nb = max(nb_corrs) if nb_corrs else 0.0
            weights[i] = 1.0 if max_nb > 0.6 else 0.1
    return weights

