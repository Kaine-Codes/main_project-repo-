def to_fp32_bits(val):
    return struct.unpack('>I', struct.pack('>f', val))[0]

def from_fp32_bits(bits):
    return struct.unpack('>f', struct.pack('>I', bits))[0]

# Method 1: Pure Python float64 (gold reference)
sum_sq_f64 = sum(x**2 for x in raw_values)
mp_f64 = sum_sq_f64 / 256
print(f"=== Method 1: Python float64 (gold reference) ===")
print(f"  Sum of squares: {sum_sq_f64:.6f}")
print(f"  Mean power:     {mp_f64:.6f}")

# Method 2: Simulate FP32 arithmetic (what hardware does)
# Convert each value to FP32, square in FP32, accumulate in FP32
acc = 0.0
for x in raw_values:
    x_fp32 = from_fp32_bits(to_fp32_bits(x))  # round to FP32
    sq_fp32 = from_fp32_bits(to_fp32_bits(x_fp32 * x_fp32))  # square in FP32
    acc_new = acc + sq_fp32
    acc = from_fp32_bits(to_fp32_bits(acc_new))  # accumulate in FP32

# Division by 256 via exponent subtract
