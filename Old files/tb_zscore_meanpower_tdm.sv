    // ---------------------------------------------------------------
    // Gold reference: compute expected mean power per channel (float64)
    // ---------------------------------------------------------------
    real gold_mean_power [0:N_CH-1];
    real gold_mu  [0:N_CH-1];
    real gold_inv [0:N_CH-1];

    initial begin
        gold_mu[0]  = MU_F_CH0;      gold_inv[0] = INV_SIG_F_CH0;
        gold_mu[1]  = MU_F_CH1;      gold_inv[1] = INV_SIG_F_CH1;

        for (int ch = 0; ch < N_CH; ch++) begin
            real sum_sq;
            sum_sq = 0.0;
            for (int k = 0; k < NUM; k++) begin
                real raw_val, z_exact;
                raw_val = (ch == 0) ? ch0_values[k] : ch1_values[k];
                z_exact = (raw_val - gold_mu[ch]) * gold_inv[ch];
                // Clamp to +/-6
                if (z_exact >  6.0) z_exact =  6.0;
                if (z_exact < -6.0) z_exact = -6.0;
                sum_sq = sum_sq + (z_exact * z_exact);
            end
            gold_mean_power[ch] = sum_sq / NUM;
        end
    end

    // ---------------------------------------------------------------
    // Main test sequence
    // ---------------------------------------------------------------
    integer  i;
    longint  start_time, end_time;

    initial begin
        $display("================================================================");
        $display("  Fused Z-Score + Mean Power TDM — %0d Electrode Testbench", N_CH);
        $display("  Pipeline: subtract → multiply → clamp → square → accumulate → store");
        $display("================================================================");
        $display("  Ch0: mu=%f (Q8.16=%0d)  inv=%f (Q4.12=%0d)",
                 MU_F_CH0, MU_CH0, INV_SIG_F_CH0, INV_SIG_CH0);
        $display("  Ch1: mu=%f (Q8.16=%0d)  inv=%f (Q4.12=%0d)",
                 MU_F_CH1, MU_CH1, INV_SIG_F_CH1, INV_SIG_CH1);
        $display("================================================================");

        // --- Reset ---
        rst_n       = 0;
        batch_valid = 0;
        x_batch[0]  = '0;
        x_batch[1]  = '0;

        // Wire calibration register file
        mu_reg[0]      = MU_CH0;       mu_reg[1]      = MU_CH1;
        inv_sig_reg[0] = INV_SIG_CH0;  inv_sig_reg[1] = INV_SIG_CH1;

        repeat (5) @(posedge clk);
        rst_n = 1;
        repeat (2) @(posedge clk);

        start_time = $time;

        // --- Feed 256 batches (back-to-back, no batch_done wait) ---
        // Each batch: assert batch_valid for 1 cycle, then wait for FSM to
        // finish feeding N_CH channels (2 cycles for N_CH=2), plus 1 idle.
        for (i = 0; i < NUM; i++) begin
            @(posedge clk);
            x_batch[0]  <= real_to_q8_16(ch0_values[i]);
            x_batch[1]  <= real_to_q8_16(ch1_values[i]);
            batch_valid <= 1'b1;

            @(posedge clk);
            batch_valid <= 1'b0;

            // Wait for FSM to return to IDLE (N_CH cycles for feed phase)
            repeat (N_CH) @(posedge clk);
        end

        // Wait for pipeline drain + window_valid
        repeat (20) @(posedge clk);
        end_time = $time;

        // --- Check if window_valid fired ---
        // (It should have fired by now; if not, we'll report failure below)

        // --- Results ---
        $display("");
        $display("================================================================");
        $display("  RESULTS SUMMARY");
        $display("================================================================");
        for (int ch = 0; ch < N_CH; ch++) begin
            real hw_mp, err, pct_err;
            hw_mp   = q4_12_to_real(mean_power[ch]);
            err     = (hw_mp > gold_mean_power[ch]) ?
                      (hw_mp - gold_mean_power[ch]) :
                      (gold_mean_power[ch] - hw_mp);
            pct_err = (gold_mean_power[ch] != 0.0) ?
                      (err / gold_mean_power[ch]) * 100.0 : 0.0;

            $display("  --- Channel %0d ---", ch);
            $display("    Mean Power (HW,  Q4.12): 0x%04h = %.6f", mean_power[ch], hw_mp);
            $display("    Mean Power (GOLD, f64):          %.6f", gold_mean_power[ch]);
            $display("    Absolute error:                  %.8f", err);
            $display("    Relative error:                  %.4f%%", pct_err);
        end
        $display("  Processing time: %0d ns (%0d cycles)",
                 end_time - start_time,
                 integer'((end_time - start_time) / CLK_PERIOD));
        $display("================================================================");

        // --- Pass/Fail ---
        begin
            int pass = 1;
            for (int ch = 0; ch < N_CH; ch++) begin
                real hw_mp, pct_err;
                hw_mp   = q4_12_to_real(mean_power[ch]);
                pct_err = (gold_mean_power[ch] != 0.0) ?
                    (((hw_mp > gold_mean_power[ch]) ?
                      (hw_mp - gold_mean_power[ch]) :
                      (gold_mean_power[ch] - hw_mp)) / gold_mean_power[ch]) * 100.0 : 0.0;
                if (pct_err > 5.0) begin
                    $display("  *** FAIL: Ch%0d relative error %.4f%% exceeds 5%% ***",
                             ch, pct_err);
                    pass = 0;
                end
            end
            if (pass) $display("  *** PASS — All channels within 5%% error ***");
        end
        $display("================================================================");
        $finish;
    end

    // ---------------------------------------------------------------
